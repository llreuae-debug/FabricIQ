const STORAGE_KEY_LANG = 'texcost_preferred_language';

export class I18nService {
  private currentLanguage: LanguageCode = 'en';

  constructor() {
    this.init();
  }

  private init() {
    try {
      const savedLang = localStorage.getItem(STORAGE_KEY_LANG);
      if (savedLang && savedLang in LANGUAGES) {
        this.currentLanguage = savedLang as LanguageCode;
      }
    } catch {
      // ignore
    }
  }

  public detectInitialLanguage(): { suggestedLang: LanguageCode; reason: string } {
    try {
      const languages = navigator.languages || [navigator.language || ''];
      const langStr = languages.join(',').toLowerCase();

      if (langStr.includes('ur') || langStr.includes('pk')) {
        return { suggestedLang: 'ur', reason: 'Detected Urdu / Pakistan system locale' };
      }
      if (langStr.includes('tr')) {
        return { suggestedLang: 'tr', reason: 'Detected Turkish system locale' };
      }
      if (langStr.includes('ar')) {
        return { suggestedLang: 'ar', reason: 'Detected Arabic system locale' };
      }
      if (langStr.includes('zh')) {
        return { suggestedLang: 'zh', reason: 'Detected Chinese system locale' };
      }
    } catch {
      // fallback
    }
    return { suggestedLang: 'en', reason: 'Default International Language' };
  }

  public getLanguage(): LanguageCode {
    return this.currentLanguage;
  }

  public setLanguage(code: LanguageCode): void {
    if (code in LANGUAGES) {
      this.currentLanguage = code;
      try {
        localStorage.setItem(STORAGE_KEY_LANG, code);
        const config = LANGUAGES[code];
        document.documentElement.setAttribute('dir', config.dir);
        document.documentElement.setAttribute('lang', config.code);
      } catch {
        // ignore
      }
    }
  }

  public t(key: string): string {
    const dict = TRANSLATIONS[this.currentLanguage] || TRANSLATIONS.en;
    if (key in dict) {
      return dict[key];
    }
    return TRANSLATIONS.en[key] || key;
  }

  public getDir(): 'ltr' | 'rtl' {
    return LANGUAGES[this.currentLanguage]?.dir || 'ltr';
  }
}

export const i18n = new I18nService();
